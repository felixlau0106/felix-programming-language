from enum import Enum, auto
from dataclasses import dataclass
from typing import Any

# Comparing integers is faster than string comparison. So we define TokenType as subclass of Enum!
# If we do this:
# class TokenType:
#     LPAREN = "("
# When we later compare it using tok.type == TokenType.LPAREN it will be a string comparison!

class TokenType(Enum):
    # Single-character tokens
    LPAREN = auto() # (
    RPAREN = auto() # )
    LBRACKET = auto() # [
    RBRACKET = auto() # ]
    LBRACE = auto() # {
    RBRACE = auto() # }    
    COMMA = auto() # ,
    DOT = auto() # .
    PLUS = auto() # +
    MINUS = auto() # -
    STAR = auto() # *
    SLASH = auto() # /
    PERCENT = auto() # %
    COLON = auto() # :
    EQUAL = auto() # =
    EQUAL_EQUAL = auto() # ==
    BANG_EQUAL = auto() # !=
    LESS = auto() # <
    LESS_EQUAL = auto() # <=
    GREATER = auto() # >
    GREATER_EQUAL = auto() # >=
    ARROW = auto() # ->

    # Separators
    SEMICOLON = auto() # ;
    NEWLINE = auto() # \n

    # multi-character tokens / literals
    IDENT = auto() # identifier, eg: variable names, function names
    NUMBER = auto() # numeric literal, eg: 123, 3.14
    STRING = auto() # string literal, eg: "hello world"

    # keywords
    DEF = auto() # def, used to define a function
    END = auto() # end, universal END for blocks
    IF = auto() # if, used for conditional statements
    ELIF = auto() # elif, used for conditional statements
    ELSE = auto() # else, used for conditional statements
    WHILE = auto() # while, used for loops
    SWITCH = auto() # C style switch
    CASE = auto()
    DEFAULT = auto()
    FN = auto() # fn, used for anonymous functions
    TRUE = auto() # True with upper T
    FALSE = auto() # False with upper F
    AND = auto() # and or AND
    OR = auto() # or or OR
    NOT = auto() # not or NOT
    RETURN = auto() # return
    EOF = auto() # end of file, used to indicate the end of the source code
    ERROR = auto() # error, used to indicate an error in the source code

@dataclass
class Token:
    type: TokenType # the tag
    lexeme: str # exact text from source code
    literal: Any # interpreted value
    line: int # row
    column: int # optional but common

class Lexer:
    def __init__(self, source: str):
        self.source = source
        self.start = 0 # start of the current lexeme
        self.current = 0 # how far we have read in the source code
        self.line = 1 # line number
        self.column = 1 # column number
        self.tokens: list[Token] = [] # list of tokens generated by the lexer

    def scan_tokens(self) -> list[Token]:
        while not self.is_at_end():
            self.start = self.current
            self.scan_token()
        self.tokens.append(Token(TokenType.EOF, "", None, self.line, self.column))
        return self.tokens

    def is_at_end(self) -> bool:
        return self.current >= len(self.source)

    def advance(self) -> str:
        self.current += 1
        self.column += 1
        return self.source[self.current - 1]

    def peek(self) -> str:
        if self.is_at_end():
            return '\0'
        return self.source[self.current]

    def peek_next(self) -> str:
        # To future me: You might think `Why don't we just let it crash with an IndexError?`
        # *** A compiler should be robust and handle edge cases gracefully, providing meaningful feedback to the user rather than crashing unexpectedly!
        # Without this check users might get an IndexError when they try to peek next at the end of the source code. 
        # This is especially important for cases like numbers where we want to check if the next character is a digit after a decimal point.
        if self.current + 1 >= len(self.source):
            return '\0'
        return self.source[self.current + 1]

    def add_token(self, type: TokenType, literal=None) -> None:
        text = self.source[self.start:self.current]
        col = self.column - (self.current - self.start) 
        # eg: main() when we add LPAREN, start is 4; current is 5 pointing at `)` because we already ate `(`, col is 6 because we are on `)` right now. 6-(5-4) = 5 = correct col of LPAREN
        self.tokens.append(Token(type, text, literal, self.line, col))

    def error(self, c: str, message:str = None, suggestion: str = None, offset: int = 0) -> None:
        RED = "\033[91m"
        YELLOW = "\033[93m"
        GRAY = "\033[90m"
        RESET = "\033[0m"
        
        line_number_string = str(self.line)
        margin_width = max(3, len(line_number_string))
        margin = " " * margin_width

        print(f"{RED}Error[Line {self.line}, Col {self.column}]: Lexer Error -> {message or f'Unexpected character: \"{c}\"'}{RESET}")
        print(f"{GRAY}{margin} |{RESET}")

        padded_line = line_number_string.rjust(margin_width)
        source_code = self.source.splitlines()[self.line - 1]
        print(f"{GRAY}{padded_line} |{RESET} {source_code}")
        print(f"{GRAY}{margin} |{RESET} {RED}" + " " * (self.column - 1 + offset) + f"^{RESET}")

        if suggestion:
            print(f"{GRAY}{margin} |{RESET}")
            print(f"{YELLOW}{margin} = Help: {suggestion}{RESET}")
        print(f"\n{GRAY}" + "─" * 60 + f"{RESET}\n")
        self.add_token(TokenType.ERROR, c) # add an error token to the list of tokens so the parser can handle it gracefully

    def identifier(self) -> None:
        while self.peek().isalpha() or self.peek().isdigit() or self.peek() == "_":
            self.advance()
        match self.source[self.start:self.current]:
            case "def":
                self.add_token(TokenType.DEF)
            case "end":
                self.add_token(TokenType.END)
            case "if":
                self.add_token(TokenType.IF)
            case "elif":
                self.add_token(TokenType.ELIF)
            case "else":
                self.add_token(TokenType.ELSE)
            case "while":
                self.add_token(TokenType.WHILE)
            case "switch":
                self.add_token(TokenType.SWITCH)
            case "case":
                self.add_token(TokenType.CASE)
            case "default":
                self.add_token(TokenType.DEFAULT)
            case "fn":
                self.add_token(TokenType.FN)
            case "True":
                self.add_token(TokenType.TRUE, literal=True)
            case "False":
                self.add_token(TokenType.FALSE, literal=False)
            case "and" | "AND":
                self.add_token(TokenType.AND)
            case "or" | "OR":
                self.add_token(TokenType.OR)
            case "not" | "NOT":
                self.add_token(TokenType.NOT)
            case "return":
                self.add_token(TokenType.RETURN)
            case _:
                self.add_token(TokenType.IDENT)

    def number(self) -> None:
        while self.peek().isdigit():
            self.advance()
        if self.peek() == ".":
            if not self.peek_next().isdigit():
                suggestion = "Do you mean to write a number like 3.14?"
                self.error(".", None, suggestion, 0)
                return
            self.advance() # consume the "."
            while self.peek().isdigit():
                self.advance()
        # We need to feed the correct literal value to the TokenType.NUMBER token. If the number has a decimal point, we should convert it to a float; otherwise, we convert it to an int.
        raw = self.source[self.start:self.current]
        if "." in raw:
            value = float(raw)
        else:
            value = int(raw)
        self.add_token(TokenType.NUMBER, value)

    def string(self) -> None:
        while self.peek() != "\"" and not self.is_at_end():
            if self.peek() == "\n": # if we reach a newline before finding the closing quote, it's an unterminated string literal
                return self.error("\"", "Unterminated string literal.", "Did you forget to close the string with a double quote?", 0)
            self.advance() # eating next char until we find the closing quote or reach the end of the source code

        if self.is_at_end(): # if we reach the end of the source code before finding the closing quote, it's an unterminated string literal
            return self.error("\"", "Unterminated string literal.", "Did you forget to close the string with a double quote?", 0)

        # While loop ended, meaning we found the closing quote
        self.advance() # consume the closing quote
        value = self.source[self.start + 1:self.current - 1] # exclude the quotes
        self.add_token(TokenType.STRING, value)

    def scan_token(self) -> None:
        c = self.advance() # return the last c then current and col plus 1. meaning in "main()" it eats m but current is already pointing at a
        match c:
            case '\n':
                self.add_token(TokenType.NEWLINE)
                self.line += 1
                self.column = 1
            case ' ' | '\r' | '\t':
                pass
            case ';':
                self.add_token(TokenType.SEMICOLON)
            case '(':
                self.add_token(TokenType.LPAREN)
            case ')':
                self.add_token(TokenType.RPAREN)
            case '[':
                self.add_token(TokenType.LBRACKET)
            case ']':
                self.add_token(TokenType.RBRACKET)
            case '{':
                self.add_token(TokenType.LBRACE)
            case '}':
                self.add_token(TokenType.RBRACE)
            case ',':
                self.add_token(TokenType.COMMA)
            case '.':
                self.add_token(TokenType.DOT)
            case '+':
                self.add_token(TokenType.PLUS)
            case '-':
                if self.peek() == ">":
                    self.advance()
                    self.add_token(TokenType.ARROW)
                else:
                    self.add_token(TokenType.MINUS)
            case '*':
                self.add_token(TokenType.STAR)
            case '/':
                self.add_token(TokenType.SLASH)
            case '%':
                self.add_token(TokenType.PERCENT)
            case ':':
                self.add_token(TokenType.COLON)
            case '!':
                if self.peek() == "=":
                    self.advance()
                    self.add_token(TokenType.BANG_EQUAL)
                else:
                    self.error(c, None, None, -1)
            case '=':
                if self.peek() in ["<", ">"]:
                    bad_char = self.advance() # eat the bad char! ("<" or ">")
                    suggestion = "Do you mean to write '<='?" if bad_char == "<" else "Do you mean to write '>='?"
                    self.error(bad_char, None, suggestion, -1)
                elif self.peek() == "=":
                    self.advance()
                    self.add_token(TokenType.EQUAL_EQUAL)
                else:
                    self.add_token(TokenType.EQUAL)
            case '<':
                if self.peek() == "=":
                    self.advance()
                    self.add_token(TokenType.LESS_EQUAL)
                else:
                    self.add_token(TokenType.LESS)
            case '>':
                if self.peek() == "=":
                    self.advance()
                    self.add_token(TokenType.GREATER_EQUAL)
                else:
                    self.add_token(TokenType.GREATER)
            case '\"':
                self.string()
            case '#':
                while self.peek() != '\n' and not self.is_at_end():
                    self.advance()
            case _:
                if c.isalpha() or c == "_":
                    self.identifier()
                elif c.isdigit():
                    self.number()
                else:
                    self.error(c, None, None, -1)

                

